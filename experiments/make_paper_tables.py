def tier2(
    csv_name: str = "tier2.csv", suffix: str = "", prefix: str = "tier", extra: str | None = None
) -> None:
    """Tier-1 vs. Tier-2 parity and gate G1 (tier2_study.csv, LOG L28, L29).

    ``suffix`` names the outputs (``tab_tier2<suffix>.tex`` ...) and ``prefix`` the LaTeX
    macros (``\\<prefix>TwoAvatar``); the held-out seeds use ``_heldout`` and ``held``. ``extra``
    adds the rows of a second CSV (another fleet's runs on the same seeds) when it exists.
    """
    rows = _read(csv_name)
    if extra and (DATA / extra).exists():
        rows += _read(extra)
    tiers = [t for t in TIER_NAMES if any(r["tier"] == t for r in rows)]
    lines = [
        f"% generated by experiments/make_paper_tables.py from {csv_name}; {_provenance(rows)}",
        "\\begin{tabular}{lcccccc}",
        "\\toprule",
        "Perception & Team & At [s] & Wrong & G1 & \\avatar{} [m] & Oracle [m] \\\\",
        "\\midrule",
    ]
    macros = [f"% generated from {csv_name}"]
    for t in tiers:
        if t == "T2":
            lines.append("\\multicolumn{7}{l}{Tier 2 (Gazebo, kinematic rigs, sonar proxy):} \\\\")
        if t == "T2s":
            lines.append("\\multicolumn{7}{l}{Tier 2, DAVE's sonar images on the BlueROV2s:} \\\\")
        if t == "T2p":
            lines.append(
                "\\multicolumn{7}{l}{Tier 2, as above, with a Ping360 on each BlueROV2:} \\\\"
            )
        sel = [r for r in rows if r["tier"] == t]
        merged = sum(int(r["n_connected"]) == int(r["n_slam"]) for r in sel)
        # Median over the runs that merged (a run without a common frame has no time).
        times = [t for t in (_num(r["team_connected_s"]) for r in sel) if np.isfinite(t)]
        at = float(np.median(times)) if times else float("nan")
        wrong = sum(int(r["wrong_alignments"]) for r in sel)
        n_al = sum(int(r["alignments"]) for r in sel)
        g1 = sum(r["g1_pass"] == "True" for r in sel)
        av = mean_ci([_num(r["team_ate_avatar_m"]) for r in sel])
        orc = mean_ci([_num(r["team_ate_oracle_robust_m"]) for r in sel])
        lines.append(
            f"{ROW_NAMES[t]} & {merged}/{len(sel)} & {'--' if np.isnan(at) else f'{at:.0f}'} & "
            f"{wrong}/{n_al} & "
            f"{g1}/{len(sel)} & {av} & {orc} \\\\"
        )
        tag = TIER_TAGS[t]
        macros += [
            f"\\newcommand{{\\{prefix}{tag}Avatar}}"
            f"{{{np.mean([_num(r['team_ate_avatar_m']) for r in sel]):.2f}}}",
            f"\\newcommand{{\\{prefix}{tag}Median}}"
            f"{{{np.median([_num(r['team_ate_avatar_m']) for r in sel]):.2f}}}",
            f"\\newcommand{{\\{prefix}{tag}Oracle}}"
            f"{{{np.mean([_num(r['team_ate_oracle_robust_m']) for r in sel]):.2f}}}",
            f"\\newcommand{{\\{prefix}{tag}At}}{{{at:.0f}}}",
            f"\\newcommand{{\\{prefix}{tag}Wrong}}{{{wrong}/{n_al}}}",
            f"\\newcommand{{\\{prefix}{tag}GOne}}{{{g1}/{len(sel)}}}",
            f"\\newcommand{{\\{prefix}{tag}Merged}}{{{merged}/{len(sel)}}}",
            f"\\newcommand{{\\{prefix}{tag}Runs}}{{{len(sel)}}}",
        ]
    lines += ["\\bottomrule", "\\end{tabular}"]
    (DATA / f"tab_tier2{suffix}.tex").write_text("\n".join(lines) + "\n")
    (DATA / f"tier2{suffix}_summary.tex").write_text("\n".join(macros) + "\n")

    # Per-robot ATE [m]: alone vs. Avatar (own frame, fused graph), mean over seeds.
    tiers = [t for t in tiers if t in AGENT_TIERS]
    head = " & ".join(f"\\multicolumn{{2}}{{c}}{{{TIER_NAMES[t].split(',')[-1].strip()}}}"
                      if t != "T1" else "\\multicolumn{2}{c}{Tier 1}" for t in tiers)  # fmt: skip
    lines = [
        f"% generated by experiments/make_paper_tables.py from {csv_name}; {_provenance(rows)}",
        "\\begin{tabular}{l" + "cc" * len(tiers) + "}",
        "\\toprule",
        f" & {head} \\\\",
        "Robot" + " & Alone & \\avatar{}" * len(tiers) + " \\\\",
        "\\midrule",
    ]
    for name, label in FLEET:
        cells = []
        for t in tiers:
            sel = [r for r in rows if r["tier"] == t]
            a = np.mean([_num(r[f"ate_solo_{name}_m"]) for r in sel])
            f = np.mean([_num(r[f"ate_fused_{name}_m"]) for r in sel])
            cells += [f"{a:.2f}", f"{f:.2f}"]
        lines.append(f"{label} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    (DATA / f"tab_tier2{suffix}_agents.tex").write_text("\n".join(lines) + "\n")


def write_environment() -> None:
    """Record the software and hardware the paper data were generated with (LOG L33)."""
    import os
    import platform
    import sys

    import scipy

    cpu = next(
        (
            ln.split(":", 1)[1].strip()
            for ln in open("/proc/cpuinfo")
            if ln.startswith("model name")
        ),
        platform.processor(),
    )
    lines = [
        "# Environment of paper/data (written by experiments/make_paper_tables.py).",
        "# The numbers depend on the NumPy/SciPy versions: see avatar_py/requirements-lock.txt.",
        f"host: {platform.node()}",
        f"python: {sys.version.split()[0]}",
        f"numpy: {np.__version__}",
        f"scipy: {scipy.__version__}",
        f"cpu: {cpu}, {os.cpu_count()} threads",
    ]
    (DATA / "environment.txt").write_text("\n".join(lines) + "\n")


