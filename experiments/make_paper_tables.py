#!/usr/bin/env python3
"""LaTeX tables for the manuscript from ``paper/data/*.csv`` (AGENTS.md §5).

Reads only CSVs written by the experiment scripts and writes ``paper/data/tab_*.tex``,
which the manuscript includes with ``\\input``. Never edit the generated files by hand.

    python experiments/make_paper_tables.py
"""

from __future__ import annotations

import csv
from pathlib import Path

import numpy as np
from scipy import stats

DATA = Path(__file__).resolve().parents[1] / "paper" / "data"
PROFILE_NAMES = {
    "m64": "M64 (64\\,bit/s)",
    "x150": "X150 class (100\\,bit/s)",
    "acoustic_generic": "Generic (1\\,kbit/s)",
}


def _read(name: str) -> list[dict]:
    with (DATA / name).open(newline="") as f:
        return list(csv.DictReader(f))


def _num(v: str) -> float:
    return float(v) if v not in ("", "None", "nan") else float("nan")


def mean_ci(values: list[float]) -> str:
    """``mean ± half-width`` of the 95 % t-interval (``–`` if empty)."""
    v = np.array([x for x in values if np.isfinite(x)])
    if len(v) == 0:
        return "--"
    if len(v) == 1:
        return f"{v[0]:.3f}"
    half = stats.t.ppf(0.975, len(v) - 1) * v.std(ddof=1) / np.sqrt(len(v))
    return f"{v.mean():.3f} $\\pm$ {half:.3f}"


def _provenance(rows: list[dict]) -> str:
    commits = sorted({r["commit"] for r in rows})
    seeds = sorted({int(r["seed"]) for r in rows})
    return f"commit {', '.join(commits)}; seeds {seeds[0]}--{seeds[-1]} ({len(seeds)})"


def server_vs_avatar() -> None:
    rows = _read("server_vs_avatar.csv")
    n_agents = max(int(r["n_connected"]) for r in rows)
    lines = [
        f"% generated by experiments/make_paper_tables.py from server_vs_avatar.csv; "
        f"{_provenance(rows)}",
        "\\begin{tabular}{llcccc}",
        "\\toprule",
        "Acoustic link & Method & Team & Connected & AUV keyframes & Team ATE [m] \\\\",
        " & & merged & at [s] & at server & (merged runs) \\\\",
        "\\midrule",
    ]
    profiles = list(dict.fromkeys(r["acoustic"] for r in rows))
    for p in profiles:
        methods = list(dict.fromkeys((r["method"], r["acoustic_stride"]) for r in rows
                                     if r["acoustic"] == p))  # fmt: skip
        for j, (m, stride) in enumerate(methods):
            sel = [r for r in rows if r["acoustic"] == p and r["method"] == m
                   and r["acoustic_stride"] == stride]  # fmt: skip
            full = [r for r in sel if int(r["n_connected"]) == n_agents]
            label = {"avatar": "\\avatar{}", "server": f"Server, stride {stride}",
                     "oracle": "Oracle"}[m]  # fmt: skip
            conn = [_num(r["team_connected_s"]) for r in sel]
            conn = [c for c in conn if np.isfinite(c)]
            conn_s = f"{np.median(conn):.0f}" if conn else "--"
            uuv = [_num(r["uuv_delivered_fraction"]) for r in sel]
            uuv_s = f"{100 * np.nanmean(uuv):.0f}\\,\\%" if np.isfinite(uuv).any() else "--"
            if m == "oracle":
                conn_s = uuv_s = "--"
            first = PROFILE_NAMES.get(p, p) if j == 0 else ""
            lines.append(
                f"{first} & {label} & {len(full)}/{len(sel)} & {conn_s} & {uuv_s} & "
                f"{mean_ci([_num(r['team_ate_m']) for r in full])} \\\\"
            )
        lines.append("\\midrule" if p != profiles[-1] else "\\bottomrule")
    lines.append("\\end{tabular}")
    (DATA / "tab_server_vs_avatar.tex").write_text("\n".join(lines) + "\n")


def cycle_check() -> None:
    rows = _read("association_cycle_check.csv")
    tot = {k: sum(int(r[k]) for r in rows) for k in
           ("accepted_alignments", "possible_alignments", "wrong_alignments",
            "wrong_after_cycle_check", "correct_vetoed")}  # fmt: skip
    prec = np.nanmean([_num(r["pair_precision"]) for r in rows])
    lines = [
        f"% generated by experiments/make_paper_tables.py from association_cycle_check.csv; "
        f"{_provenance(rows)}",
        "\\begin{tabular}{lc}",
        "\\toprule",
        f"Accepted alignments & {tot['accepted_alignments']} / {tot['possible_alignments']} \\\\",
        f"Landmark-pair precision (mean) & {prec:.3f} \\\\",
        f"Wrong alignments, before the cycle check & {tot['wrong_alignments']} \\\\",
        f"Wrong alignments, after & {tot['wrong_after_cycle_check']} \\\\",
        f"Correct alignments vetoed & {tot['correct_vetoed']} \\\\",
        "\\bottomrule",
        "\\end{tabular}",
    ]
    (DATA / "tab_cycle_check.tex").write_text("\n".join(lines) + "\n")


def bandwidth_sweep() -> None:
    rows = _read("bandwidth_sweep.csv")
    scheds = list(dict.fromkeys(r["scheduler"] for r in rows))
    rates = sorted({float(r["acoustic_bps"]) for r in rows})
    names = {"fifo": "FIFO", "quality": "Quality (v0)", "voi": "VoI"}
    head = " & ".join(f"\\multicolumn{{2}}{{c}}{{{names.get(s, s)}}}" for s in scheds)
    sub = " & ".join("merged & at [s]" for _ in scheds)
    lines = [
        f"% generated by experiments/make_paper_tables.py from bandwidth_sweep.csv; "
        f"{_provenance(rows)}",
        "\\begin{tabular}{l" + "cc" * len(scheds) + "}",
        "\\toprule",
        f"Acoustic & {head} \\\\",
        f"{{[bit/s]}} & {sub} \\\\",  # braces: a leading [ would be read as \\'s option
        "\\midrule",
    ]
    for bps in rates:
        cells = []
        for sch in scheds:
            sel = [r for r in rows if float(r["acoustic_bps"]) == bps and r["scheduler"] == sch]
            merged = sum(r["team_merged"] == "True" for r in sel)
            conn = [_num(r["team_connected_s"]) for r in sel]
            conn = [c for c in conn if np.isfinite(c)]
            cells.append(f"{merged}/{len(sel)} & {np.median(conn):.0f}" if conn else
                         f"{merged}/{len(sel)} & --")  # fmt: skip
        lines.append(f"{bps:.0f} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    (DATA / "tab_bandwidth.tex").write_text("\n".join(lines) + "\n")


def drift_correction() -> None:
    """Per-run table for H1 in the small-drift regime (decision D8)."""
    rows = _read("drift_anchored.csv")
    agent = "uuv_1"
    runs = sorted(rows, key=lambda r: _num(r[f"ate_alone_{agent}_m"]))
    lines = [
        f"% generated by experiments/make_paper_tables.py from drift_anchored.csv; "
        f"{_provenance(rows)}",
        "\\begin{tabular}{rcccc}",
        "\\toprule",
        "Seed & Alone [m] & \\avatar{} [m] & Change & Oracle [m] \\\\",
        "\\midrule",
    ]
    small = []
    for r in runs:
        a, f, o = (_num(r[f"ate_{k}_{agent}_m"]) for k in ("alone", "fused", "oracle"))
        change = 100.0 * (f - a) / a
        mark = "" if a <= 1.0 else "$^\\dagger$"
        if a <= 1.0:
            small.append(change)
        lines.append(f"{r['seed']}{mark} & {a:.2f} & {f:.2f} & {change:+.0f}\\,\\% & {o:.2f} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    (DATA / "tab_drift.tex").write_text("\n".join(lines) + "\n")
    mean = f"{np.mean(small):+.0f}" if small else "--"
    (DATA / "drift_summary.tex").write_text(
        f"% generated from drift_anchored.csv\n\\newcommand{{\\driftSmallRuns}}{{{len(small)}}}\n"
        f"\\newcommand{{\\driftSmallMeanChange}}{{{mean}}}\n"
    )


def realism() -> None:
    """Team ATE under front-end errors for each robust kernel (LOG L25)."""
    rows = _read("realism.csv")
    kernels = list(dict.fromkeys(r["kernel"] for r in rows))
    names = {"none": "None", "huber:3": "Huber ($k{=}3$)", "gnc:4.03": "GNC-TLS"}
    head = " & ".join(names.get(k, k) for k in kernels)
    lines = [
        f"% generated by experiments/make_paper_tables.py from realism.csv; {_provenance(rows)}",
        "\\begin{tabular}{ll" + "c" * len(kernels) + "}",
        "\\toprule",
        f"Preset & Front-end errors & {head} \\\\",
        "\\midrule",
    ]
    presets = list(dict.fromkeys(r["preset"] for r in rows))
    levels = {"none": "none", "low": "5\\,\\% + 0.5", "high": "15\\,\\% + 1.0"}
    n_agents = max(int(r["n_connected_dec"]) for r in rows)
    for p_ in presets:
        for j, lv in enumerate(dict.fromkeys(r["errors"] for r in rows if r["preset"] == p_)):
            cells = []
            for k in kernels:
                sel = [r for r in rows if r["preset"] == p_ and r["errors"] == lv
                       and r["kernel"] == k]  # fmt: skip
                ate = np.mean([_num(r["team_ate_dec_m"]) for r in sel])
                merged = sum(int(r["n_connected_dec"]) == n_agents for r in sel)
                note = "" if merged == len(sel) else f" ({merged}/{len(sel)})"
                cells.append(f"{ate:.2f}{note}" if ate < 10 else f"{ate:.0f}{note}")
            name = p_.replace("fleet_", "").replace("_", "\\_") if j == 0 else ""
            lines.append(f"{name} & {levels.get(lv, lv)} & " + " & ".join(cells) + " \\\\")
        lines.append("\\midrule" if p_ != presets[-1] else "\\bottomrule")
    lines.append("\\end{tabular}")
    (DATA / "tab_realism.tex").write_text("\n".join(lines) + "\n")


def main() -> None:
    made = []
    for fn, src in ((server_vs_avatar, "server_vs_avatar.csv"),
                    (cycle_check, "association_cycle_check.csv"),
                    (bandwidth_sweep, "bandwidth_sweep.csv"),
                    (drift_correction, "drift_anchored.csv"),
                    (realism, "realism.csv")):  # fmt: skip
        if (DATA / src).exists():
            fn()
            made.append(src)
        else:
            print(f"skip: paper/data/{src} missing (run `make -C experiments paper-data`)")
    print(f"tables from: {made}")


if __name__ == "__main__":
    main()
