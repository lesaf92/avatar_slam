def bandwidth_sweep() -> None:
    rows = _read("bandwidth_sweep.csv")
    scheds = list(dict.fromkeys(r["scheduler"] for r in rows))
    rates = sorted({float(r["acoustic_bps"]) for r in rows})
    names = {"fifo": "FIFO", "quality": "Quality (v0)", "voi": "VoI"}
    head = " & ".join(f"\\multicolumn{{2}}{{c}}{{{names.get(s, s)}}}" for s in scheds)
    sub = " & ".join("merged & at [s]" for _ in scheds)
    lines = [
        f"% generated by experiments/make_paper_tables.py from bandwidth_sweep.csv; "
        f"{_provenance(rows)}",
        "\\begin{tabular}{l" + "cc" * len(scheds) + "}",
        "\\toprule",
        f"Acoustic & {head} \\\\",
        f"{{[bit/s]}} & {sub} \\\\",  # braces: a leading [ would be read as \\'s option
        "\\midrule",
    ]
    for bps in rates:
        cells = []
        for sch in scheds:
            sel = [r for r in rows if float(r["acoustic_bps"]) == bps and r["scheduler"] == sch]
            merged = sum(r["team_merged"] == "True" for r in sel)
            conn = [_num(r["team_connected_s"]) for r in sel]
            conn = [c for c in conn if np.isfinite(c)]
            cells.append(f"{merged}/{len(sel)} & {np.median(conn):.0f}" if conn else
                         f"{merged}/{len(sel)} & --")  # fmt: skip
        lines.append(f"{bps:.0f} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    (DATA / "tab_bandwidth.tex").write_text("\n".join(lines) + "\n")


def loss_sweep() -> None:
    """Team merges (median time [s]) vs. acoustic packet loss, per rate and order (T-C5-01)."""
    rows = _read("loss_sweep.csv")
    scheds = list(dict.fromkeys(r["scheduler"] for r in rows))
    rates = sorted({float(r["acoustic_bps"]) for r in rows})
    losses = sorted({float(r["acoustic_loss"]) for r in rows})
    names = {"fifo": "FIFO", "quality": "Quality", "voi": "VoI"}
    head = " & ".join(f"\\multicolumn{{{len(scheds)}}}{{c}}{{{b:.0f}\\,bit/s}}" for b in rates)
    sub = " & ".join(names.get(s, s) for _ in rates for s in scheds)
    lines = [
        f"% generated by experiments/make_paper_tables.py from loss_sweep.csv; {_provenance(rows)}",
        "\\begin{tabular}{l" + "c" * len(scheds) * len(rates) + "}",
        "\\toprule",
        f"Packet & {head} \\\\",
        f"loss & {sub} \\\\",
        "\\midrule",
    ]
    for loss in losses:
        cells = []
        for bps in rates:
            for sch in scheds:
                sel = [r for r in rows if float(r["acoustic_bps"]) == bps
                       and float(r["acoustic_loss"]) == loss and r["scheduler"] == sch]  # fmt: skip
                conn = [c for c in (_num(r["team_connected_s"]) for r in sel) if np.isfinite(c)]
                at = f" ({np.median(conn):.0f})" if conn else ""
                cells.append(f"{sum(r['team_merged'] == 'True' for r in sel)}/{len(sel)}{at}")
        lines.append(f"{100 * loss:.0f}\\,\\% & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    (DATA / "tab_loss.tex").write_text("\n".join(lines) + "\n")


def loss_confirm() -> None:
    """Pre-registered paired test of the digest orders under heavy loss (LOG L47): macros."""
    rows = _read("loss_confirm.csv")
    merged = {}
    for r in rows:
        merged.setdefault(r["scheduler"], {})[(r["seed"], r["acoustic_loss"])] = (
            r["team_merged"] == "True"
        )
    macros = [f"% generated from loss_confirm.csv; {_provenance(rows)}"]
    names = {"fifo": "Fifo", "quality": "Quality", "voi": "Voi"}
    for s, m in merged.items():
        macros.append(f"\\newcommand{{\\lossConfirm{names[s]}}}{{{sum(m.values())}/{len(m)}}}")
    for a, b in (("voi", "fifo"), ("voi", "quality")):
        win = sum(merged[a][k] and not merged[b][k] for k in merged[a])
        lose = sum(merged[b][k] and not merged[a][k] for k in merged[a])
        pval = stats.binomtest(win, win + lose).pvalue if win + lose else 1.0
        tag = f"{names[a]}{names[b]}"
        macros += [
            f"\\newcommand{{\\lossConfirm{tag}Pairs}}{{{win}:{lose}}}",
            f"\\newcommand{{\\lossConfirm{tag}P}}{{{pval:.2g}}}",
        ]
    (DATA / "loss_confirm.tex").write_text("\n".join(macros) + "\n")


def drift_correction() -> None:
    """Per-run table for H1 in the small-drift regime (decision D8)."""
    rows = _read("drift_anchored.csv")
    agent = "uuv_1"
    runs = sorted(rows, key=lambda r: _num(r[f"ate_alone_{agent}_m"]))
    lines = [
        f"% generated by experiments/make_paper_tables.py from drift_anchored.csv; "
        f"{_provenance(rows)}",
        "\\begin{tabular}{rcccc}",
        "\\toprule",
        "Seed & Alone [m] & \\avatar{} [m] & Change & Oracle [m] \\\\",
        "\\midrule",
    ]
    small = _small_drift_changes(rows, agent)
    for r in runs:
        a, f, o = (_num(r[f"ate_{k}_{agent}_m"]) for k in ("alone", "fused", "oracle_own"))
        change = 100.0 * (f - a) / a
        mark = "" if a <= 1.0 else "$^\\dagger$"
        lines.append(f"{r['seed']}{mark} & {a:.2f} & {f:.2f} & {change:+.0f}\\,\\% & {o:.2f} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    (DATA / "tab_drift.tex").write_text("\n".join(lines) + "\n")
    mean = f"{np.mean(small):+.0f}" if small else "--"
    team = np.mean([_num(r["team_ate_dec_m"]) for r in rows])
    macros = [
        "% generated from drift_anchored.csv (and drift_anchored_noscale.csv, D15)",
        f"\\newcommand{{\\driftSmallRuns}}{{{len(small)}}}",
        f"\\newcommand{{\\driftSmallMeanChange}}{{{mean}}}",
        f"\\newcommand{{\\driftTeamAte}}{{{team:.2f}}}",
        f"\\newcommand{{\\driftSmallWorse}}{{{sum(c > 0 for c in small)}}}",
        f"\\newcommand{{\\driftSmallMaxWorse}}{{{max(small):.0f}}}",
    ]
    if (DATA / "drift_anchored_noscale.csv").exists():  # estimator without the scale states
        ns = _read("drift_anchored_noscale.csv")
        small_ns = _small_drift_changes(ns, agent)
        team_ns = np.mean([_num(r["team_ate_dec_m"]) for r in ns])
        macros += [
            f"\\newcommand{{\\driftNoScaleSmallRuns}}{{{len(small_ns)}}}",
            f"\\newcommand{{\\driftNoScaleSmallMeanChange}}{{{np.mean(small_ns):+.0f}}}",
            f"\\newcommand{{\\driftNoScaleTeamAte}}{{{team_ns:.2f}}}",
        ]
    (DATA / "drift_summary.tex").write_text("\n".join(macros) + "\n")


def _small_drift_changes(rows: list[dict], agent: str) -> list[float]:
    """Change [%] of ``agent``'s ATE, fused vs. alone, over the runs with solo ATE ≤ 1 m (D8)."""
    out = []
    for r in rows:
        a, f = _num(r[f"ate_alone_{agent}_m"]), _num(r[f"ate_fused_{agent}_m"])
        if a <= 1.0:
            out.append(100.0 * (f - a) / a)
    return out


def realism() -> None:
    """Team ATE under front-end errors for each robust kernel (LOG L25; 20 seeds, T-S1-10).

    A cell is ``median / mean`` [m]; ``[n]``: runs that failed (the team did not merge, or its
    ATE exceeds 1 m). Means alone are fragile: one diverged run dominates them (LOG L33).
    """
    rows = _read("realism.csv")
    kernels = list(dict.fromkeys(r["kernel"] for r in rows))
    names = {"none": "None", "huber:3": "Huber ($k{=}3$)", "gnc:4.03": "GNC-TLS"}
    head = " & ".join(names.get(k, k) for k in kernels)
    lines = [
        f"% generated by experiments/make_paper_tables.py from realism.csv; {_provenance(rows)}",
        "\\begin{tabular}{ll" + "c" * len(kernels) + "}",
        "\\toprule",
        f"Preset & Front-end errors & {head} \\\\",
        "\\midrule",
    ]
    presets = list(dict.fromkeys(r["preset"] for r in rows))
    levels = {
        "none": "none",
        "low": "5\\,\\% + 0.5",
        "high": "15\\,\\% + 1.0",
        "burst_low": "5\\,\\% in bursts + 0.5",
        "burst_high": "13\\,\\% in bursts + 1.0",
        "split_half": "half of revisits split",
        "split_all": "all revisits split",
    }
    n_agents = max(int(r["n_connected_dec"]) for r in rows)
    for p_ in presets:
        for j, lv in enumerate(dict.fromkeys(r["errors"] for r in rows if r["preset"] == p_)):
            cells = []
            for k in kernels:
                sel = [r for r in rows if r["preset"] == p_ and r["errors"] == lv
                       and r["kernel"] == k]  # fmt: skip
                ate = np.array([_num(r["team_ate_dec_m"]) for r in sel])
                failed = sum(
                    int(r["n_connected_dec"]) < n_agents or a > 1.0
                    for r, a in zip(sel, ate, strict=True)
                )
                med, mean = np.median(ate), np.mean(ate)
                fmt = lambda v: f"{v:.2f}" if v < 10 else f"{v:.0f}"  # noqa: E731
                cells.append(f"{fmt(med)} / {fmt(mean)}" + (f" [{failed}]" if failed else ""))
            name = p_.replace("fleet_", "").replace("_", "\\_") if j == 0 else ""
            lines.append(f"{name} & {levels.get(lv, lv)} & " + " & ".join(cells) + " \\\\")
        lines.append("\\midrule" if p_ != presets[-1] else "\\bottomrule")
    lines.append("\\end{tabular}")
    (DATA / "tab_realism.tex").write_text("\n".join(lines) + "\n")


